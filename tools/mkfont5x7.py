#!/usr/bin/env python3
"""
Writes src/font5x7.c: the X11 misc-fixed 5x7 font ("Public domain font. Share and enjoy."), ASCII 32-126,
as 5 column bytes per glyph (bit 0 = the top pixel) - the layout of an SSD1306/SH1106 OLED page.
usage: tools/mkfont5x7.py <5x7.pcf>   (from the Debian package xfonts-base: /usr/share/fonts/X11/misc/5x7.pcf.gz, gunzipped)
"""
import sys, os
from PIL import PcfFontFile
f = PcfFontFile.PcfFontFile(open(sys.argv[1], "rb"))
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "font5x7.c")
lines = []
for ch in range(32, 127):
    cols = [0] * 5
    g = f.glyph[ch]
    if g:
        (dx, dy), (x0, y0, x1, y1), src, im = g
        for y in range(im.size[1]):
            for x in range(im.size[0]):
                if im.getpixel((x, y)):
                    px, py = x0 + x, 6 + y0 + y          # baseline at row 6 (ascent 6, descent 1)
                    if 0 <= px < 5 and 0 <= py < 8: cols[px] |= 1 << py
    c = chr(ch)
    lines.append("  {%s}, /* %s */" % (",".join("0x%02x" % v for v in cols), "'\\''" if c == "'" else "'\\\\'" if c == "\\" else repr(c)))
with open(out, "w") as o:
    o.write("/* GENERATED by tools/mkfont5x7.py from the X11 misc-fixed 5x7 font (public domain: \"Share and enjoy.\")\n"
            " * ASCII 32-126, 5 columns per glyph, bit 0 = top pixel (OLED page layout) */\n")
    o.write("const unsigned char font5x7[95][5] = {\n%s\n};\n" % "\n".join(lines))
print("wrote", out)
