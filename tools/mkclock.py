#!/usr/bin/env python3
"""
Writes src/fontclock.c: thin clock digits "0123456789:-" rendered from DejaVu Sans (Bitstream Vera license,
like src/font.c), cropped to the ink, for the big clock on the OLED ('display time').
Each size: height H, per glyph a width (<= 32) and H row words (bit 31 = the left pixel).
usage: tools/mkclock.py   (needs /usr/share/fonts/truetype/dejavu/DejaVuSans.ttf and Pillow)
"""
import os
from PIL import Image, ImageDraw, ImageFont
TTF = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
CH = "0123456789:-"
THR = 190                      # a high threshold = thinner strokes

def glyphs(size):
    f = ImageFont.truetype(TTF, size)
    top, bot = 10**9, -1
    ims = []
    for c in CH:
        im = Image.new("L", (size * 2, size * 2), 0)
        ImageDraw.Draw(im).text((size // 2, size // 2), c, font=f, fill=255)
        im = im.point(lambda v: 255 if v > THR else 0)
        ims.append(im)
        if c.isdigit():
            bb = im.getbbox(); top = min(top, bb[1]); bot = max(bot, bb[3])
    out = []
    for c, im in zip(CH, ims):
        bb = im.getbbox()
        x0, x1 = (bb[0], bb[2]) if bb else (0, size // 4)
        if c == "-": x0, x1 = x0, x1
        rows = []
        for y in range(top, bot):
            w = 0
            for x in range(x0, x1):
                if im.getpixel((x, y)): w |= 1 << (31 - (x - x0))
            rows.append(w)
        out.append((x1 - x0, rows))
    return bot - top, out

def emit(name, size, o):
    h, gl = glyphs(size)
    o.write("/* %s: DejaVu Sans %d px -> digits %d px tall */\n" % (name, size, h))
    o.write("const int %s_h = %d;\n" % (name, h))
    o.write("const unsigned char %s_w[%d] = { %s };\n" % (name, len(CH), ", ".join(str(w) for w, _ in gl)))
    o.write("const unsigned int %s_g[%d][%d] = {\n" % (name, len(CH), h))
    for c, (w, rows) in zip(CH, gl):
        o.write("  { %s }, /* '%s' */\n" % (",".join("0x%08x" % r for r in rows), c))
    o.write("};\n")
    widths = {c: w for c, (w, _) in zip(CH, gl)}
    return h, widths

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "fontclock.c")
with open(out, "w") as o:
    o.write("/* GENERATED by tools/mkclock.py - clock digits \"0123456789:-\" from DejaVu Sans (Bitstream Vera license) */\n")
    for name, size in (("clk_big", 40), ("clk_sec", 20)):
        h, w = emit(name, size, o)
        hm = 4 * max(w[c] for c in "0123456789") + w[":"] + 4 * 3
        print(name, size, "height", h, "HH:MM width (widest digits, gap 3)", hm, "two digits", 2 * max(w[c] for c in "0123456789") + 2)
print("wrote", out)
