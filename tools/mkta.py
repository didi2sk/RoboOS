#!/usr/bin/env python3
"""
Writes src/ta_roots.h: the root certificates RoboOS trusts for HTTPS downloads ('update get'),
as BearSSL trust anchors (subject DN + public key), from the PEM files of the host's CA store.
Large public CAs only (GitHub's raw files are Let's Encrypt -> ISRG Root X1).
usage: tools/mkta.py [/etc/ssl/certs]
"""
import os, sys
from cryptography import x509
from cryptography.hazmat.primitives.asymmetric import rsa, ec

ROOTS = ["ISRG_Root_X1", "ISRG_Root_X2", "DigiCert_Global_Root_CA", "DigiCert_Global_Root_G2", "DigiCert_Global_Root_G3",
         "USERTrust_RSA_Certification_Authority", "USERTrust_ECC_Certification_Authority",
         "Sectigo_Public_Server_Authentication_Root_R46", "Sectigo_Public_Server_Authentication_Root_E46",
         "GTS_Root_R1", "GTS_Root_R2", "GTS_Root_R3", "GTS_Root_R4", "GlobalSign_Root_CA_-_R3", "GlobalSign_Root_R46",
         "Baltimore_CyberTrust_Root", "Amazon_Root_CA_1", "Amazon_Root_CA_3",
         # more big public CAs (0.56, for api.anthropic.com and other APIs whose CA is not known in advance)
         "DigiCert_TLS_RSA4096_Root_G5", "DigiCert_TLS_ECC_P384_Root_G5", "SSL.com_TLS_RSA_Root_CA_2022",
         "SSL.com_TLS_ECC_Root_CA_2022", "SSL.com_Root_Certification_Authority_RSA", "SSL.com_Root_Certification_Authority_ECC",
         "Certainly_Root_R1", "Certainly_Root_E1", "Microsoft_RSA_Root_Certificate_Authority_2017",
         "Microsoft_ECC_Root_Certificate_Authority_2017", "IdenTrust_Commercial_Root_CA_1"]
d = sys.argv[1] if len(sys.argv) > 1 else "/etc/ssl/certs"
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "ta_roots.h")

def arr(name, b):
    s = ", ".join("0x%02x" % x for x in b)
    return "static const unsigned char %s[%d] = { %s };\n" % (name, len(b), s)

body, tas, names = "", [], []
for r in ROOTS:
    p = os.path.join(d, r + ".pem")
    if not os.path.exists(p):
        print("skip (not in the store):", r)
        continue
    c = x509.load_pem_x509_certificate(open(p, "rb").read())
    i = len(tas)
    dn = c.subject.public_bytes()
    body += arr("ta%d_dn" % i, dn)
    k = c.public_key()
    if isinstance(k, rsa.RSAPublicKey):
        n = k.public_numbers().n.to_bytes((k.key_size + 7) // 8, "big")
        e = k.public_numbers().e.to_bytes((k.public_numbers().e.bit_length() + 7) // 8, "big")
        body += arr("ta%d_n" % i, n) + arr("ta%d_e" % i, e)
        tas.append("{ { (unsigned char *)ta%d_dn, sizeof ta%d_dn }, BR_X509_TA_CA, { BR_KEYTYPE_RSA, { .rsa = "
                   "{ (unsigned char *)ta%d_n, sizeof ta%d_n, (unsigned char *)ta%d_e, sizeof ta%d_e } } } }" % ((i,) * 6))
    elif isinstance(k, ec.EllipticCurvePublicKey):
        curve = {"secp256r1": "BR_EC_secp256r1", "secp384r1": "BR_EC_secp384r1", "secp521r1": "BR_EC_secp521r1"}[k.curve.name]
        from cryptography.hazmat.primitives import serialization
        q = k.public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
        body += arr("ta%d_q" % i, q)
        tas.append("{ { (unsigned char *)ta%d_dn, sizeof ta%d_dn }, BR_X509_TA_CA, { BR_KEYTYPE_EC, { .ec = "
                   "{ %s, (unsigned char *)ta%d_q, sizeof ta%d_q } } } }" % (i, i, curve, i, i))
    else:
        print("skip (key type):", r); continue
    names.append(r)

with open(out, "w") as f:
    f.write("/* GENERATED by tools/mkta.py - root CAs for HTTPS downloads: %s */\n" % ", ".join(names))
    f.write(body)
    f.write("static const br_x509_trust_anchor ta_roots[%d] = {\n    %s\n};\n" % (len(tas), ",\n    ".join(tas)))
print("wrote", out, len(tas), "roots")
