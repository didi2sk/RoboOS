#!/usr/bin/env python3
"""
Writes src/<name>.c from an X11 misc-fixed bitmap font (public domain: "Share and enjoy."), ASCII 32-126,
as <w> column bytes per glyph (bit 0 = the top pixel) - the layout of an SSD1306/SH1106 OLED page.
usage: tools/mkfont_x11.py <font.pcf> <name> <w> <h> <ascent>
  tools/mkfont_x11.py 5x7.pcf font5x7 5 7 6      (fonts from the Debian package xfonts-base,
  tools/mkfont_x11.py 4x6.pcf font4x6 4 6 5       /usr/share/fonts/X11/misc/*.pcf.gz, gunzipped)
"""
import sys, os
from PIL import PcfFontFile
pcf, name, W, H, ASC = sys.argv[1], sys.argv[2], int(sys.argv[3]), int(sys.argv[4]), int(sys.argv[5])
f = PcfFontFile.PcfFontFile(open(pcf, "rb"))
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", name + ".c")
lines = []
for ch in range(32, 127):
    cols = [0] * W
    g = f.glyph[ch]
    if g:
        (dx, dy), (x0, y0, x1, y1), src, im = g
        for y in range(im.size[1]):
            for x in range(im.size[0]):
                if im.getpixel((x, y)):
                    px, py = x0 + x, ASC + y0 + y         # y0 is negative: rows above the baseline
                    if 0 <= px < W and 0 <= py < H: cols[px] |= 1 << py
    c = chr(ch)
    lines.append("  {%s}, /* %s */" % (",".join("0x%02x" % v for v in cols), "'\\''" if c == "'" else "'\\\\'" if c == "\\" else repr(c)))
with open(out, "w") as o:
    o.write("/* GENERATED by tools/mkfont_x11.py from the X11 misc-fixed %dx%d font (public domain: \"Share and enjoy.\")\n"
            " * ASCII 32-126, %d columns per glyph, bit 0 = top pixel (OLED page layout) */\n" % (W, H, W))
    o.write("const unsigned char %s[95][%d] = {\n%s\n};\n" % (name, W, "\n".join(lines)))
print("wrote", out)
